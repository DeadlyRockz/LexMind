import { NEVER_RULES } from '../domain/advice-boundary.ts';

/**
 * The disclosures, in one place, so the UI, the CLI and every export carry the same words.
 *
 * Two requirements drive this file.
 *
 * **EU AI Act Article 50(1)** requires that people are informed they are interacting with an AI
 * system, and **50(5)** requires the information "at the latest at the time of the first
 * interaction", in a clear and distinguishable manner, meeting accessibility requirements.
 * Article 50 has been in force since 2 August 2026. So the disclosure sits on the upload screen,
 * before anything is uploaded — not in a footer.
 *
 * **Provider data use.** On the unpaid Gemini tier, Google's Additional Terms say submitted
 * content is used to improve its products and machine-learning technologies, and that human
 * reviewers may read API input and output. LexMind redacts before transmitting, but redaction is
 * imperfect, so it discloses transmission regardless of how well redaction performed. That is
 * also why the demo documents are synthetic and labelled as synthetic.
 */

export const AI_DISCLOSURE = {
  heading: 'Before you upload',
  isAi: 'LexMind is an AI tool. It reads the document you give it and explains what it says. It is not a lawyer and it does not give legal advice.',
  transmission:
    'If an AI provider key is configured, the text of your document is sent to Google’s Gemini API to produce the plain-English explanations. Names, addresses, ID numbers and account numbers are replaced with stand-ins before anything is sent, and put back only on your screen.',
  freeTier:
    'On Google’s free tier, Google uses submitted content to improve its products, and human reviewers may read it. Automated redaction is a strong mitigation, not a guarantee — roughly one name in eight is missed by tools of this kind. Do not upload a document you could not share.',
  localOnly:
    'With no provider key configured, nothing leaves this machine. LexMind still finds deposits over the local limit, one-sided notice periods, entry rights, repair duties and prohibited clauses — all of that is computed locally.',
  notAdvice:
    'LexMind gives legal information, not legal advice. It will not tell you whether to sign, predict what a court will do, or draft a document for you. It will help you prepare for a conversation with someone who can.',
} as const;

export const NO_ADVICE_SUMMARY: readonly string[] = NEVER_RULES;

/**
 * The honest accuracy statement.
 *
 * These are published figures about purpose-built legal AI, and they are the argument for
 * LexMind's architecture rather than a disclaimer bolted on beside it: if tools built on curated
 * legal corpora hallucinate at these rates, a tool reading one uploaded PDF has no basis for
 * claiming better, which is exactly why nothing is shown without a citation verified in code.
 */
export const ACCURACY_NOTE = [
  'Purpose-built legal AI built on curated legal databases still gets things wrong 17 to 33 per cent',
  'of the time, and general-purpose models answering legal questions do far worse. LexMind has no',
  'basis for claiming better, so it is built the other way round: the model explains and extracts,',
  'every quote is checked against your document in code, and anything that fails that check is',
  'discarded rather than shown. Statements about the law come from a human-verified table of',
  'provisions, never from the model.',
].join(' ');

export interface ExportFooterOptions {
  readonly jurisdictionLabel: string;
  readonly jurisdictionCoverage: string;
  readonly generatedOn: Date;
  readonly modelLabel: string;
  readonly redactionSummary?: Readonly<Record<string, number>>;
}

/**
 * The footer every export carries.
 *
 * Exports travel: the markdown gets pasted into an email to a lawyer, the printable view gets
 * forwarded. So the disclosure, the advice boundary, the jurisdiction caveat and the date have to
 * travel with the document rather than living in the app the reader has already closed.
 */
export function exportFooter(options: ExportFooterOptions): string {
  const redactions =
    options.redactionSummary === undefined
      ? []
      : Object.entries(options.redactionSummary)
          .filter(([, count]) => count > 0)
          .map(([kind, count]) => `${count} ${kind}`);

  return [
    '---',
    '',
    '## About this document',
    '',
    `Generated by LexMind on ${options.generatedOn.toISOString().slice(0, 10)}.`,
    `Language model: ${options.modelLabel}.`,
    '',
    `**Jurisdiction:** ${options.jurisdictionLabel}. ${options.jurisdictionCoverage}`,
    '',
    `**This is legal information, not legal advice.** ${AI_DISCLOSURE.notAdvice}`,
    '',
    'LexMind never:',
    ...NEVER_RULES.map((rule) => `- ${rule}`),
    '',
    `**Accuracy.** ${ACCURACY_NOTE}`,
    ...(redactions.length === 0
      ? []
      : [
          '',
          `**Privacy.** Before any text was sent to the language model, LexMind replaced ${redactions.join(', ')} with stand-ins, and restored them only for this document. The mapping was never stored or transmitted.`,
        ]),
    '',
    'Rules are current as of the retrieval date shown against each citation. Tenancy law changes:',
    "England's regime changed materially on 1 May 2026, and California's deposit cap changed on",
    '1 July 2024. Check anything you intend to rely on.',
  ].join('\n');
}
